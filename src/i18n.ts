const DICTS: Record<Lang, Record<string, string>> = { zh, en }

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const tmpl = DICTS[lang][key] ?? zh[key] ?? key
  if (!vars) return tmpl
  return tmpl.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

interface LangState {
  lang: Lang
  setLang: (l: Lang) => void
}

export const useLang = create<LangState>()(
  persist(
    (set) => ({
      lang: 'zh',
      setLang: (lang) => set({ lang }),
    }),
    { name: 'neko-lang' },
  ),
)

/** 组件内取文案：语言切换时自动重渲染 */
export function useT() {
  const lang = useLang((s) => s.lang)
  return useMemo(
    () => (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang],
  )
}

export function fmtDate(ts: number | string | Date): string {
  const d = new Date(ts)
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

export function greetingKey(): string {
  const h = new Date().getHours()
  if (h < 5) return 'home.greetingNight'
  if (h < 11) return 'home.greetingMorning'
  if (h < 18) return 'home.greetingAfternoon'
  return 'home.greetingEvening'
}
